# Python has three logical operator and, or, not 

# and operator example 
a = 555
b = 90
c = 899
if c > b and c > a: 
    print("c is greater than a and b")

# or operator example 
if a < b or a < c: 
    print("a is at least smaller than one number from b and c")

# not operator 
if not a > c:
    print("a is not greater than c") 

